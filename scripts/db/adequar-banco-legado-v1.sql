    data_inicio                 DATE                     NOT NULL,
    data_fim                    DATE,
    valor_frete                 NUMERIC(15, 2),
    km_inicial_vazio            INTEGER,
    km_inicial_carregado        INTEGER,
    km_final_carregado          INTEGER,
    consumo_medio_vazio         NUMERIC(4, 2),
    consumo_medio_carregado     NUMERIC(4, 2),
    criado_por_id               BIGINT                   NOT NULL,
    criada_em                   TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizada_em               TIMESTAMP WITH TIME ZONE NOT NULL,
    finalizada_em               TIMESTAMP WITH TIME ZONE,
    cadastro_retroativo_em      TIMESTAMP WITH TIME ZONE,
    origem_preco_diesel         VARCHAR(30),
    preco_diesel_valor_pago     NUMERIC(17, 2),
    preco_diesel_litros         NUMERIC(14, 3),
    preco_diesel_medio          NUMERIC(10, 4),
    viagem_referencia_preco_id  BIGINT,
    referencia_consolidada_em   TIMESTAMP WITH TIME ZONE,
    resultado_consolidado_em    TIMESTAMP WITH TIME ZONE,
    politica_calculo_versao     VARCHAR(40),
    limite_preco_diesel_minimo  NUMERIC(12, 4),
    limite_preco_diesel_maximo  NUMERIC(12, 4),
    limite_consumo_minimo       NUMERIC(12, 4),
    limite_consumo_maximo       NUMERIC(12, 4),
    res_receita                 NUMERIC(15, 2),
    res_km_vazio                INTEGER,
    res_km_carregado            INTEGER,
    res_litros_vazio            NUMERIC(14, 3),
    res_litros_carregado        NUMERIC(14, 3),
    res_custo_diesel_vazio      NUMERIC(17, 2),
    res_custo_diesel_carregado  NUMERIC(17, 2),
    res_custo_arla              NUMERIC(17, 2),
    res_pedagios                NUMERIC(17, 2),
