CREATE TABLE IF NOT EXISTS despesas_viagem (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    viagem_id      BIGINT                   NOT NULL,
    tipo           VARCHAR(10)              NOT NULL,
    descricao      VARCHAR(200),
