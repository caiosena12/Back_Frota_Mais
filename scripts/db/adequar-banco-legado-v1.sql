    criado_em      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_despesas_viagem_viagem FOREIGN KEY (viagem_id) REFERENCES viagens (id),
    CONSTRAINT fk_despesas_viagem_criado_por FOREIGN KEY (criado_por_id) REFERENCES usuarios (id),
    CONSTRAINT ck_despesas_viagem_tipo CHECK (tipo IN ('PEDAGIO', 'EXTRA'))
);

-- 5. Nomes da V1. Cada restrição é achada pela tabela, tipo e definição.
CREATE OR REPLACE FUNCTION pg_temp.renomear(tabela TEXT, tipo "char", definicao TEXT, novo TEXT)
RETURNS VOID LANGUAGE plpgsql AS $$
DECLARE atual TEXT;
BEGIN
    SELECT c.conname INTO atual FROM pg_constraint c
    WHERE c.conrelid = ('public.' || tabela)::regclass AND c.contype = tipo
      AND regexp_replace(pg_get_constraintdef(c.oid), '::[a-z ]+(\[\])?', '', 'g') = definicao;
    IF atual IS NULL THEN
        RAISE EXCEPTION 'Restrição esperada não encontrada em %: %', tabela, definicao;
    END IF;
    IF atual <> novo THEN
        EXECUTE format('ALTER TABLE %I RENAME CONSTRAINT %I TO %I', tabela, atual, novo);
    END IF;
END $$;

SELECT pg_temp.renomear('usuarios', 'u', 'UNIQUE (email)', 'uk_usuarios_email');
SELECT pg_temp.renomear('usuarios', 'f', 'FOREIGN KEY (empresa_id) REFERENCES empresas(id)', 'fk_usuarios_empresa');
SELECT pg_temp.renomear('usuarios', 'c', 'CHECK (((perfil)= ANY ((ARRAY[''DONO'', ''MOTORISTA'']))))', 'ck_usuarios_perfil');
SELECT pg_temp.renomear('caminhoes', 'u', 'UNIQUE (empresa_id, placa)', 'uk_caminhoes_empresa_placa');
SELECT pg_temp.renomear('caminhoes', 'f', 'FOREIGN KEY (empresa_id) REFERENCES empresas(id)', 'fk_caminhoes_empresa');
SELECT pg_temp.renomear('caminhoes', 'c', 'CHECK (((status)= ANY ((ARRAY[''ATIVO'', ''INATIVO'']))))', 'ck_caminhoes_status');
SELECT pg_temp.renomear('viagens', 'f', 'FOREIGN KEY (empresa_id) REFERENCES empresas(id)', 'fk_viagens_empresa');
SELECT pg_temp.renomear('viagens', 'f', 'FOREIGN KEY (caminhao_id) REFERENCES caminhoes(id)', 'fk_viagens_caminhao');
SELECT pg_temp.renomear('viagens', 'f', 'FOREIGN KEY (criado_por_id) REFERENCES usuarios(id)', 'fk_viagens_criado_por');
SELECT pg_temp.renomear('viagens', 'c', 'CHECK (((status)= ANY ((ARRAY[''EM_ANDAMENTO'', ''FINALIZADA'']))))', 'ck_viagens_status');
SELECT pg_temp.renomear('viagens', 'c', 'CHECK (((origem_preco_diesel)= ANY ((ARRAY[''ABASTECIMENTOS_DA_VIAGEM'', ''ULTIMO_PRECO_DO_CAMINHAO'', ''SEM_REFERENCIA'']))))', 'ck_viagens_origem_preco_diesel');
SELECT pg_temp.renomear('abastecimentos', 'f', 'FOREIGN KEY (viagem_id) REFERENCES viagens(id)', 'fk_abastecimentos_viagem');
SELECT pg_temp.renomear('abastecimentos', 'f', 'FOREIGN KEY (criado_por_id) REFERENCES usuarios(id)', 'fk_abastecimentos_criado_por');
SELECT pg_temp.renomear('abastecimentos', 'c', 'CHECK (((tipo)= ANY ((ARRAY[''DIESEL'', ''ARLA'']))))', 'ck_abastecimentos_tipo');
SELECT pg_temp.renomear('despesas_viagem', 'f', 'FOREIGN KEY (viagem_id) REFERENCES viagens(id)', 'fk_despesas_viagem_viagem');
SELECT pg_temp.renomear('despesas_viagem', 'f', 'FOREIGN KEY (criado_por_id) REFERENCES usuarios(id)', 'fk_despesas_viagem_criado_por');
SELECT pg_temp.renomear('despesas_viagem', 'c', 'CHECK (((tipo)= ANY ((ARRAY[''PEDAGIO'', ''EXTRA'']))))', 'ck_despesas_viagem_tipo');

-- 6. Conferência: o conjunto de tabelas tem de ser exatamente o da V1.
DO $$
DECLARE tabelas TEXT;
BEGIN
    SELECT string_agg(table_name, ',' ORDER BY table_name) INTO tabelas
    FROM information_schema.tables WHERE table_schema = 'public' AND table_type = 'BASE TABLE';
    IF tabelas <> 'abastecimentos,caminhoes,despesas_viagem,empresas,usuarios,viagens' THEN
        RAISE EXCEPTION 'Tabelas inesperadas após a adequação: %', tabelas;
    END IF;
END $$;

COMMIT;
