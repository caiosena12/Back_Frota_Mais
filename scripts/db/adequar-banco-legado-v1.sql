-- Adequa um banco criado pelo antigo ddl-auto=update do Hibernate ao estado
-- exato da migration V1 (src/main/resources/db/migration/V1__schema_inicial.sql),
-- para que o Flyway possa marcá-lo como baseline na versão 1.
--
-- NÃO é uma migration: não roda sozinho. Siga docs/MIGRATIONS.md, que exige
-- backup antes. Roda numa única transação: qualquer erro desfaz tudo.
--
-- O que faz:
--   1. Aborta se a coluna legada caminhoes.apelido tiver algum valor (nada é
--      descartado sem decisão humana).
--   2. Remove a restrição legada UNIQUE(placa) global, que contraria a regra
--      de placa única por empresa. Nenhum dado é removido.
--   3. Remove a coluna vazia caminhoes.apelido.
--   4. Cria as tabelas que faltam (viagens, abastecimentos, despesas_viagem)
--      com a definição da V1.
--   5. Renomeia restrições e índices gerados pelo Hibernate (nomes aleatórios)
--      para os nomes da V1, identificando cada um pela definição.
--   6. Confere o resultado e aborta se algo não bater.

\set ON_ERROR_STOP on
BEGIN;

-- Nunca rodar no banco de testes por engano.
DO $$
BEGIN
    IF current_database() LIKE '%test%' THEN
        RAISE EXCEPTION 'Banco % parece ser de testes; o script é para bancos legados.', current_database();
    END IF;
    IF to_regclass('public.flyway_schema_history') IS NOT NULL THEN
        RAISE EXCEPTION 'O banco já é gerenciado pelo Flyway; não use este script.';
    END IF;
END $$;

-- 1. Coluna legada apelido: só segue se estiver vazia.
DO $$
DECLARE preenchidos BIGINT;
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = 'caminhoes' AND column_name = 'apelido') THEN
        EXECUTE 'SELECT count(*) FROM caminhoes WHERE apelido IS NOT NULL' INTO preenchidos;
        IF preenchidos > 0 THEN
            RAISE EXCEPTION 'caminhoes.apelido tem % valor(es). Decida o destino desses dados antes de adequar.', preenchidos;
        END IF;
    END IF;
END $$;

-- 2. Restrições UNIQUE só sobre placa (legado).
DO $$
DECLARE r RECORD;
BEGIN
    FOR r IN
        SELECT c.conname FROM pg_constraint c
        WHERE c.conrelid = 'public.caminhoes'::regclass AND c.contype = 'u'
          AND pg_get_constraintdef(c.oid) = 'UNIQUE (placa)'
    LOOP
        EXECUTE format('ALTER TABLE caminhoes DROP CONSTRAINT %I', r.conname);
        RAISE NOTICE 'Removida restrição legada %', r.conname;
    END LOOP;
END $$;

-- 3. Coluna vazia.
ALTER TABLE caminhoes DROP COLUMN IF EXISTS apelido;

-- 4. Tabelas que um banco legado pode não ter (definição idêntica à V1).
