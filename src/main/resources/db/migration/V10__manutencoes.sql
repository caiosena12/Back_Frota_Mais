-- V10: manutenções dos caminhões. Pertencem ao histórico do caminhão, não a
-- um frete: entram no resultado mensal do caminhão e da empresa pela data, e
-- não alteram a rentabilidade de viagens. Exclusão lógica (excluida_em).
CREATE TABLE manutencoes (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id       BIGINT                   NOT NULL,
    caminhao_id      BIGINT                   NOT NULL,
    data             DATE                     NOT NULL,
    descricao        VARCHAR(500)             NOT NULL,
    valor            NUMERIC(15, 2)           NOT NULL,
    criado_por_id    BIGINT                   NOT NULL,
    criada_em        TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizada_em    TIMESTAMP WITH TIME ZONE NOT NULL,
    excluida_em      TIMESTAMP WITH TIME ZONE,
    excluida_por_id  BIGINT,
    CONSTRAINT fk_manutencoes_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id),
    CONSTRAINT fk_manutencoes_caminhao FOREIGN KEY (caminhao_id) REFERENCES caminhoes (id),
    CONSTRAINT fk_manutencoes_criado_por FOREIGN KEY (criado_por_id) REFERENCES usuarios (id),
    CONSTRAINT fk_manutencoes_excluida_por FOREIGN KEY (excluida_por_id) REFERENCES usuarios (id),
    CONSTRAINT ck_manutencoes_valor CHECK (valor > 0),
    CONSTRAINT ck_manutencoes_exclusao CHECK ((excluida_em IS NULL) = (excluida_por_id IS NULL))
);
CREATE INDEX idx_manutencoes_empresa_data ON manutencoes (empresa_id, data);
CREATE INDEX idx_manutencoes_caminhao ON manutencoes (caminhao_id);
CREATE INDEX idx_manutencoes_criado_por ON manutencoes (criado_por_id);
CREATE INDEX idx_manutencoes_excluida_por ON manutencoes (excluida_por_id);
