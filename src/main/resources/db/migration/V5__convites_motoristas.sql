-- V5: cadastro de motoristas por convite de e-mail.
--
-- O motorista é criado pelo DONO sem senha (senha_hash nulo, ativo = false):
-- ele mesmo define a senha ao aceitar o convite, e só então a conta é ativada.
-- Usuários existentes não mudam.
--
-- convites: o token enviado por e-mail nunca é gravado; só o hash SHA-256
-- dele (token_hash). Uso único (usado_em), validade (expira_em) e
-- invalidação por reenvio (invalidado_em).

ALTER TABLE usuarios ALTER COLUMN senha_hash DROP NOT NULL;
ALTER TABLE usuarios ADD CONSTRAINT ck_usuarios_pendente_inativo CHECK (senha_hash IS NOT NULL OR NOT ativo);

CREATE TABLE convites (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT                   NOT NULL,
    empresa_id     BIGINT                   NOT NULL,
    token_hash     VARCHAR(64)              NOT NULL,
    criado_por_id  BIGINT                   NOT NULL,
    criado_em      TIMESTAMP WITH TIME ZONE NOT NULL,
    expira_em      TIMESTAMP WITH TIME ZONE NOT NULL,
    usado_em       TIMESTAMP WITH TIME ZONE,
    invalidado_em  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_convites_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_convites_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT fk_convites_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id),
    CONSTRAINT fk_convites_criado_por FOREIGN KEY (criado_por_id) REFERENCES usuarios (id),
    CONSTRAINT ck_convites_expiracao CHECK (expira_em > criado_em)
);

CREATE INDEX idx_convites_usuario ON convites (usuario_id);
