-- V1: schema do Frota+ como estava no commit 3e5b9c1, quando era gerado pelo
-- Hibernate (ddl-auto=update). Serve de baseline: um banco antigo adequado
-- pelo procedimento de docs/MIGRATIONS.md fica idêntico a este estado e recebe
-- só as migrations seguintes. Não altere este arquivo: crie uma nova versão.

CREATE TABLE empresas (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(120)             NOT NULL,
    criada_em  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE usuarios (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(120) NOT NULL,
    email       VARCHAR(160) NOT NULL,
    senha_hash  VARCHAR(255) NOT NULL,
    perfil      VARCHAR(20)  NOT NULL,
    ativo       BOOLEAN      NOT NULL,
    empresa_id  BIGINT       NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT fk_usuarios_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id),
    CONSTRAINT ck_usuarios_perfil CHECK (perfil IN ('DONO', 'MOTORISTA'))
);

CREATE TABLE caminhoes (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id                BIGINT      NOT NULL,
    placa                     VARCHAR(8)  NOT NULL,
    modelo                    VARCHAR(80) NOT NULL,
    ano                       INTEGER     NOT NULL,
    status                    VARCHAR(10) NOT NULL,
    capacidade_tanque_litros  INTEGER,
    CONSTRAINT uk_caminhoes_empresa_placa UNIQUE (empresa_id, placa),
    CONSTRAINT fk_caminhoes_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id),
    CONSTRAINT ck_caminhoes_status CHECK (status IN ('ATIVO', 'INATIVO'))
);

CREATE TABLE viagens (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id                  BIGINT                   NOT NULL,
    caminhao_id                 BIGINT                   NOT NULL,
    status                      VARCHAR(20)              NOT NULL,
    origem                      VARCHAR(120),
    destino                     VARCHAR(120),
    data_inicio                 DATE                     NOT NULL,
    data_fim                    DATE,
    valor_frete                 NUMERIC(15, 2),
    km_inicial_vazio            INTEGER,
    km_inicial_carregado        INTEGER,
    km_final_carregado          INTEGER,
    consumo_medio_vazio         NUMERIC(4, 2),
    consumo_medio_carregado     NUMERIC(4, 2),
    criado_por_id               BIGINT                   NOT NULL,
    criada_em                   TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizada_em               TIMESTAMP WITH TIME ZONE NOT NULL,
    finalizada_em               TIMESTAMP WITH TIME ZONE,
    cadastro_retroativo_em      TIMESTAMP WITH TIME ZONE,
    -- Referência de preço do diesel consolidada
    origem_preco_diesel         VARCHAR(30),
    preco_diesel_valor_pago     NUMERIC(17, 2),
    preco_diesel_litros         NUMERIC(14, 3),
    preco_diesel_medio          NUMERIC(10, 4),
    viagem_referencia_preco_id  BIGINT,
    referencia_consolidada_em   TIMESTAMP WITH TIME ZONE,
    -- Fotografia financeira (ResultadoConsolidado)
    resultado_consolidado_em    TIMESTAMP WITH TIME ZONE,
    politica_calculo_versao     VARCHAR(40),
    limite_preco_diesel_minimo  NUMERIC(12, 4),
    limite_preco_diesel_maximo  NUMERIC(12, 4),
    limite_consumo_minimo       NUMERIC(12, 4),
    limite_consumo_maximo       NUMERIC(12, 4),
    res_receita                 NUMERIC(15, 2),
    res_km_vazio                INTEGER,
    res_km_carregado            INTEGER,
    res_litros_vazio            NUMERIC(14, 3),
    res_litros_carregado        NUMERIC(14, 3),
    res_custo_diesel_vazio      NUMERIC(17, 2),
    res_custo_diesel_carregado  NUMERIC(17, 2),
    res_custo_arla              NUMERIC(17, 2),
    res_pedagios                NUMERIC(17, 2),
    res_despesas_extras         NUMERIC(17, 2),
    res_custo_total             NUMERIC(17, 2),
    res_lucro                   NUMERIC(17, 2),
    res_margem                  NUMERIC(20, 2),
    res_calculo_completo        BOOLEAN,
    res_pendencias              VARCHAR(4000),
    CONSTRAINT fk_viagens_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id),
    CONSTRAINT fk_viagens_caminhao FOREIGN KEY (caminhao_id) REFERENCES caminhoes (id),
    CONSTRAINT fk_viagens_criado_por FOREIGN KEY (criado_por_id) REFERENCES usuarios (id),
    CONSTRAINT ck_viagens_status CHECK (status IN ('EM_ANDAMENTO', 'FINALIZADA')),
    CONSTRAINT ck_viagens_origem_preco_diesel CHECK (origem_preco_diesel IN
        ('ABASTECIMENTOS_DA_VIAGEM', 'ULTIMO_PRECO_DO_CAMINHAO', 'SEM_REFERENCIA'))
);

CREATE INDEX idx_viagens_empresa_caminhao ON viagens (empresa_id, caminhao_id);
CREATE INDEX idx_viagens_empresa_data_fim ON viagens (empresa_id, data_fim);

CREATE TABLE abastecimentos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    viagem_id      BIGINT                   NOT NULL,
    tipo           VARCHAR(10)              NOT NULL,
    data           DATE                     NOT NULL,
    litros         NUMERIC(10, 3)           NOT NULL,
    valor_total    NUMERIC(15, 2)           NOT NULL,
    criado_por_id  BIGINT                   NOT NULL,
    criado_em      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_abastecimentos_viagem FOREIGN KEY (viagem_id) REFERENCES viagens (id),
    CONSTRAINT fk_abastecimentos_criado_por FOREIGN KEY (criado_por_id) REFERENCES usuarios (id),
    CONSTRAINT ck_abastecimentos_tipo CHECK (tipo IN ('DIESEL', 'ARLA'))
);

CREATE TABLE despesas_viagem (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    viagem_id      BIGINT                   NOT NULL,
    tipo           VARCHAR(10)              NOT NULL,
    descricao      VARCHAR(200),
    data           DATE                     NOT NULL,
    valor          NUMERIC(15, 2)           NOT NULL,
    criado_por_id  BIGINT                   NOT NULL,
    criado_em      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_despesas_viagem_viagem FOREIGN KEY (viagem_id) REFERENCES viagens (id),
    CONSTRAINT fk_despesas_viagem_criado_por FOREIGN KEY (criado_por_id) REFERENCES usuarios (id),
    CONSTRAINT ck_despesas_viagem_tipo CHECK (tipo IN ('PEDAGIO', 'EXTRA'))
);
