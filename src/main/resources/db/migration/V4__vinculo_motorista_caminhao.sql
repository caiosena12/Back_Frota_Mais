-- V4: vínculo motorista–caminhão. Um caminhão pode ter vários motoristas e um
-- motorista vários caminhões. O motorista só enxerga os caminhões vinculados.
-- O isolamento por empresa é garantido pela aplicação (motorista e caminhão
-- da mesma empresa do DONO que cria o vínculo) e conferido nas consultas.

CREATE TABLE motorista_caminhoes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    motorista_id   BIGINT                   NOT NULL,
    caminhao_id    BIGINT                   NOT NULL,
    criado_por_id  BIGINT                   NOT NULL,
    criado_em      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_motorista_caminhoes UNIQUE (motorista_id, caminhao_id),
    CONSTRAINT fk_motorista_caminhoes_motorista FOREIGN KEY (motorista_id) REFERENCES usuarios (id),
    CONSTRAINT fk_motorista_caminhoes_caminhao FOREIGN KEY (caminhao_id) REFERENCES caminhoes (id),
    CONSTRAINT fk_motorista_caminhoes_criado_por FOREIGN KEY (criado_por_id) REFERENCES usuarios (id)
);

CREATE INDEX idx_motorista_caminhoes_caminhao ON motorista_caminhoes (caminhao_id);
