-- V8: trilha de auditoria das correções feitas pelo DONO em viagens
-- encerradas (finalizadas ou canceladas), e versões anteriores da fotografia
-- financeira. Só inclusão: nenhuma linha destas tabelas é alterada ou apagada
-- pela aplicação. O isolamento por empresa vem da viagem (viagens.empresa_id).

-- Um registro por campo alterado.
CREATE TABLE viagem_alteracoes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    viagem_id       BIGINT                   NOT NULL,
    usuario_id      BIGINT                   NOT NULL,
    alterada_em     TIMESTAMP WITH TIME ZONE NOT NULL,
    entidade        VARCHAR(20)              NOT NULL,
    registro_id     BIGINT                   NOT NULL,
    campo           VARCHAR(60)              NOT NULL,
    valor_anterior  VARCHAR(1000),
    valor_novo      VARCHAR(1000),
    CONSTRAINT fk_viagem_alteracoes_viagem FOREIGN KEY (viagem_id) REFERENCES viagens (id),
    CONSTRAINT fk_viagem_alteracoes_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT ck_viagem_alteracoes_entidade
        CHECK (entidade IN ('VIAGEM', 'ABASTECIMENTO', 'PEDAGIO', 'DESPESA_EXTRA'))
);
CREATE INDEX idx_viagem_alteracoes_viagem ON viagem_alteracoes (viagem_id, alterada_em);
CREATE INDEX idx_viagem_alteracoes_usuario ON viagem_alteracoes (usuario_id);

-- Fotografia substituída por uma correção, guardada como estava (JSON).
CREATE TABLE viagem_fotografias_anteriores (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    viagem_id         BIGINT                   NOT NULL,
    substituida_em    TIMESTAMP WITH TIME ZONE NOT NULL,
    substituida_por_id BIGINT                  NOT NULL,
    resultado         TEXT                     NOT NULL,
    CONSTRAINT fk_viagem_fotografias_viagem FOREIGN KEY (viagem_id) REFERENCES viagens (id),
    CONSTRAINT fk_viagem_fotografias_usuario FOREIGN KEY (substituida_por_id) REFERENCES usuarios (id)
);
CREATE INDEX idx_viagem_fotografias_viagem ON viagem_fotografias_anteriores (viagem_id, substituida_em);
CREATE INDEX idx_viagem_fotografias_usuario ON viagem_fotografias_anteriores (substituida_por_id);
